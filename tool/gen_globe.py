"""Generates lib/ui/servers/globe/globe_data.dart from Natural Earth 110m land.

Usage: python tool/gen_globe.py [step_degrees]
Source: https://github.com/nvkelso/natural-earth-vector (public domain).
"""
import base64
import json
import math
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tool" / ".cache" / "land.geojson"
OUT = ROOT / "lib" / "ui" / "servers" / "globe" / "globe_data.dart"
W, H = 1440, 720
STEP = float(sys.argv[1]) if len(sys.argv) > 1 else 2.1


def to_px(lon, lat):
    return ((lon + 180.0) / 360.0 * W, (90.0 - lat) / 180.0 * H)


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    img = Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(img)
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            draw.polygon([to_px(x, y) for x, y in poly[0]], fill=255)
            for hole in poly[1:]:
                draw.polygon([to_px(x, y) for x, y in hole], fill=0)
    px = img.load()

    points = []
    lat = -56.0
    while lat <= 82.0:
        ring = math.cos(math.radians(lat))
        lon_step = STEP / max(ring, 0.05)
        count = int(360.0 / lon_step)
        offset = (int(round(lat / STEP)) % 2) * 0.5
        for i in range(count):
            lon = -180.0 + (i + offset) * (360.0 / count)
            x, y = to_px(lon, lat)
            if px[min(int(x), W - 1), min(int(y), H - 1)] > 0:
                points.append((round(lat * 10), round(lon * 10)))
        lat += STEP

    raw = b"".join(struct.pack("<hh", a, b) for a, b in points)
    encoded = base64.b64encode(raw).decode("ascii")
    chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    body = "\n".join(f"    '{c}'" for c in chunks)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by tool/gen_globe.py from Natural Earth 110m land. Do not edit.\n"
        "// Little-endian int16 pairs: latitude * 10, longitude * 10.\n\n"
        f"const int kGlobePointCount = {len(points)};\n\n"
        "const String kGlobeLandPoints =\n"
        f"{body};\n",
        encoding="utf-8",
    )
    print(f"{len(points)} points -> {OUT}")


if __name__ == "__main__":
    main()
